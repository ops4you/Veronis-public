export function useTranslation() {
  const [lang, setLang] = useState<Language>(i18n.getLanguage())

  useEffect(() => {
    return i18n.subscribe((newLang) => setLang(newLang))
  }, [])

  const t = (path: string, interpolations?: Record<string, string | number>): string => {
    return translate(lang, path, interpolations)
  }

  return { t, lang, setLanguage: i18n.setLanguage }
}
